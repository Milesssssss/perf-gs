"""Fetch NVIDIA's scalar spatiotemporal blue noise into the trainer's unversioned ``.stbn/`` cache.

The upstream license is non-commercial research only, so the assets are never committed and only
downloaded on request (``scripts/data/download_stbn.py`` or the hub's prompt).
"""
from __future__ import annotations

import io
import shutil
import urllib.error
import urllib.request
import zipfile
from collections.abc import Callable
from pathlib import Path

import numpy as np
from PIL import Image

from trainer.backend.render.stbn_table import (
    NVIDIA_HEIGHT,
    NVIDIA_SLICES,
    NVIDIA_VOLUME_NAME,
    NVIDIA_WIDTH,
    default_cache_dir,
    nvidia_volume_path,
)

REPO = "NVIDIA-RTX/STBN"
BRANCH = "main"
ASSET_ZIP_URL = f"https://raw.githubusercontent.com/{REPO}/{BRANCH}/Assets/STBN.zip"
LICENSE_URL = f"https://raw.githubusercontent.com/{REPO}/{BRANCH}/License.txt"
REPO_URL = f"https://github.com/{REPO}"

# Scalar set only: the vector sets (vec2/vec3/unitvec*) are for sampling directions, not pixel masks.
SLICE_TEMPLATE = "STBN/stbn_scalar_2Dx1Dx1D_128x128x64x1_{index}.png"

LICENSE_NAME = "License.txt"
NOTICE_NAME = "NOTICE.md"

DOWNLOAD_CHUNK = 1 << 20  # 1 MiB
TIMEOUT_S = 60

LICENSE_WARNING = (
    "NOTICE: NVIDIA's spatiotemporal blue noise SDK is licensed for "
    "NON-COMMERCIAL research/evaluation use only, and redistribution must "
    "carry the license + attribution. The assets are cached OUTSIDE version "
    f"control; see {REPO_URL}/blob/{BRANCH}/License.txt for the full terms."
)


def _human_bytes(n: float) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024.0:
            return f"{n:.1f}{unit}"
        n /= 1024.0
    return f"{n:.1f}PB"


def _progress(downloaded: int, total: int) -> str:
    return f"  {_human_bytes(downloaded)} / {_human_bytes(total) if total else '?'}"


def _fetch(url: str, dest: Path, log: Callable[[str], None], *, progress: bool = True) -> None:
    """Stream ``url`` to ``dest`` via a ``.part`` rename so an interrupted transfer never looks complete."""
    part = dest.with_name(dest.name + ".part")
    part.parent.mkdir(parents=True, exist_ok=True)
    request = urllib.request.Request(
        url, headers={"User-Agent": "slang-3dgs-trainer/stbn-fetch"})
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_S) as response:
            if response.status != 200:
                raise RuntimeError(f"HTTP {response.status} for {url}")
            total = int(response.headers.get("Content-Length", 0))
            downloaded = 0
            next_report = 0
            with part.open("wb") as out:
                while chunk := response.read(DOWNLOAD_CHUNK):
                    out.write(chunk)
                    downloaded += len(chunk)
                    if progress and downloaded >= next_report:
                        log(_progress(downloaded, total))
                        next_report = downloaded + DOWNLOAD_CHUNK * 4
            if progress:
                log(_progress(downloaded, total))
    except urllib.error.URLError as exc:
        raise RuntimeError(f"failed to download {url}: {exc.reason}") from exc
    part.replace(dest)


def extract_scalar_volume(zip_path: Path) -> np.ndarray:
    """Stack the 64 scalar slices into one ``(slices, height, width)`` uint8 volume.

    Raw 8-bit values are kept, not normalized: the consumer only ranks them per tile.
    """
    with zipfile.ZipFile(zip_path) as archive:
        available = set(archive.namelist())
        missing = [SLICE_TEMPLATE.format(index=t) for t in range(NVIDIA_SLICES)
                   if SLICE_TEMPLATE.format(index=t) not in available]
        if missing:
            raise RuntimeError(
                f"{zip_path.name} is missing {len(missing)} scalar slice(s), "
                f"e.g. {missing[0]}. Upstream may have renamed the asset; check "
                f"{REPO_URL}/tree/{BRANCH}/Assets.")
        slices = []
        for index in range(NVIDIA_SLICES):
            with Image.open(io.BytesIO(
                    archive.read(SLICE_TEMPLATE.format(index=index)))) as image:
                array = np.array(image.convert("L"))
            if array.shape != (NVIDIA_HEIGHT, NVIDIA_WIDTH):
                raise RuntimeError(
                    f"slice {index} is {array.shape}, expected ({NVIDIA_HEIGHT}, {NVIDIA_WIDTH})")
            slices.append(array)
    return np.ascontiguousarray(np.stack(slices).astype(np.uint8))


def _write_notice(assets: Path, volume: np.ndarray) -> None:
    (assets / NOTICE_NAME).write_text(
        f"""# Spatiotemporal blue noise assets (third party)

Downloaded from <{REPO_URL}> (branch `{BRANCH}`), file `Assets/STBN.zip`,
scalar set `stbn_scalar_2Dx1Dx1D_128x128x64x1_*.png`.

Generated by NVIDIA's ScalarApp (void-and-cluster) and published with:

  Wolfe, Morrical, Akenine-Moller, Ramamoorthi,
  "Scalar Spatiotemporal Blue Noise Masks", arXiv:2112.09629 (EGSR 2022).

`{NVIDIA_VOLUME_NAME}` is those 64 PNG slices stacked into one
`{tuple(volume.shape)}` uint8 array — a repackaging, not a modification.

## License

NVIDIA Source Code License for Spatiotemporal Blue Noise Texture Generation
(full text in `{LICENSE_NAME}`). **Non-commercial use only** — research or
evaluation purposes. Redistribution requires shipping the license and retaining
attribution notices.

This directory is deliberately OUTSIDE version control. Do not commit it, and
do not redistribute these files without checking the license terms first.
""",
        encoding="utf-8")


def download(cache_dir: Path | None = None, *, force: bool = False, keep_zip: bool = False,
             log: Callable[[str], None] = print) -> Path:
    """Fetch + convert the scalar STBN volume to where the trainer reads it; returns its ``.npy`` path."""
    cache_dir = Path(cache_dir) if cache_dir is not None else default_cache_dir()
    volume_path = nvidia_volume_path(cache_dir)
    log(LICENSE_WARNING)
    if volume_path.is_file() and not force:
        log(f"[stbn] already present at {volume_path} — skipping "
            f"(use --force to re-download).")
        return volume_path

    zip_path = cache_dir / "download" / "STBN.zip"
    if not zip_path.is_file() or force:
        log(f"[stbn] downloading {ASSET_ZIP_URL}")
        _fetch(ASSET_ZIP_URL, zip_path, log)
    else:
        log(f"[stbn] reusing {zip_path}")

    log("[stbn] extracting the scalar 128x128x64 set ...")
    volume = extract_scalar_volume(zip_path)
    assets = volume_path.parent
    assets.mkdir(parents=True, exist_ok=True)
    log(f"[stbn] fetching {LICENSE_URL}")
    _fetch(LICENSE_URL, assets / LICENSE_NAME, log, progress=False)
    _write_notice(assets, volume)
    # Last: the trainer treats a present volume as complete, license and notice included.
    np.save(volume_path, volume)

    if not keep_zip:
        shutil.rmtree(zip_path.parent, ignore_errors=True)
    log(f"[stbn] done -> {volume_path}  {volume.shape} {volume.dtype}")
    return volume_path
